// Shell.

#include "kernel/types.h"
#include "user/user.h"
#include "kernel/fcntl.h"

// Parsed command representation
#define EXEC  1
#define REDIR 2
#define PIPE  3
#define LIST  4
#define BACK  5

#define MAXARGS 10
#define MAXJOBS 16

struct job { int pgid; int active; int stopped; };
static struct job jobs[MAXJOBS];

static int
hasprefix(char *text, char *prefix)
{
  while (*prefix)
    if (*text++ != *prefix++)
      return 0;
  return 1;
}

static void
job_add(int pgid, int stopped)
{
  int i;
  for (i = 0; i < MAXJOBS; i++) {
    if (!jobs[i].active) {
      jobs[i].pgid = pgid;
      jobs[i].stopped = stopped;
      jobs[i].active = 1;
      return;
    }
  }
  fprintf(2, "sh: job table full\n");
}

static int
job_find(int pgid)
{
  int i;
  for (i = 0; i < MAXJOBS; i++)
    if (jobs[i].active && jobs[i].pgid == pgid)
      return i;
  return -1;
}

static void
job_refresh(void)
{
  int i;
  for (i = 0; i < MAXJOBS; i++) {
    if (jobs[i].active && jobstate(jobs[i].pgid) == 0) {
      waitpg(jobs[i].pgid, 0);
      jobs[i].active = 0;
    }
  }
}

static void
job_wait(int pgid)
{
  int status, pid = waitpg(pgid, &status);
  tcsetpgrp(getpgid());
  if (pid < 0)
    return;
  if (status == -2) {
    int slot = job_find(pgid);
    if (slot < 0)
      job_add(pgid, 1);
    else
      jobs[slot].stopped = 1;
    fprintf(2, "[%d] stopped\n", pgid);
  } else {
    int slot = job_find(pgid);
    if (slot >= 0)
      jobs[slot].active = 0;
  }
}

struct cmd {
  int type;
};

struct execcmd {
  int type;
  char *argv[MAXARGS];
  char *eargv[MAXARGS];
};

struct redircmd {
  int type;
  struct cmd *cmd;
  char *file;
  char *efile;
  int mode;
  int fd;
};

struct pipecmd {
  int type;
  struct cmd *left;
  struct cmd *right;
};

struct listcmd {
  int type;
  struct cmd *left;
  struct cmd *right;
};

struct backcmd {
  int type;
  struct cmd *cmd;
};

int fork1(void); // Fork but panics on failure.
void panic(char *);
struct cmd *parsecmd(char *);
void runcmd(struct cmd *) __attribute__((noreturn));

// Execute cmd.  Never returns.
void
runcmd(struct cmd *cmd)
{
  int p[2];
  struct backcmd *bcmd;
  struct execcmd *ecmd;
  struct listcmd *lcmd;
  struct pipecmd *pcmd;
  struct redircmd *rcmd;

  if (cmd == 0)
    exit(1);

  switch (cmd->type) {
  default:
    panic("runcmd");

  case EXEC:
    ecmd = (struct execcmd *)cmd;
    if (ecmd->argv[0] == 0)
      exit(1);
    exec(ecmd->argv[0], ecmd->argv);
    fprintf(2, "exec %s failed\n", ecmd->argv[0]);
    break;

  case REDIR:
    rcmd = (struct redircmd *)cmd;
    close(rcmd->fd);
    if (open(rcmd->file, rcmd->mode) < 0) {
      fprintf(2, "open %s failed\n", rcmd->file);
      exit(1);
    }
    runcmd(rcmd->cmd);
    break;

  case LIST:
    lcmd = (struct listcmd *)cmd;
    if (fork1() == 0)
      runcmd(lcmd->left);
    wait(0);
    runcmd(lcmd->right);
    break;

  case PIPE:
    pcmd = (struct pipecmd *)cmd;
    if (pipe(p) < 0)
      panic("pipe");
    if (fork1() == 0) {
      close(1);
      dup(p[1]);
      close(p[0]);
      close(p[1]);
      runcmd(pcmd->left);
    }
    if (fork1() == 0) {
      close(0);
      dup(p[0]);
      close(p[0]);
      close(p[1]);
      runcmd(pcmd->right);
    }
    close(p[0]);
    close(p[1]);
    wait(0);
    wait(0);
    break;

  case BACK:
    bcmd = (struct backcmd *)cmd;
    if (fork1() == 0)
      runcmd(bcmd->cmd);
    break;
  }
  exit(0);
}

int
getcmd(char *buf, int nbuf)
{
  int i = 0, n;
  char c;
  write(2, "$ ", 2);
  while (i + 1 < nbuf) {
    n = read(0, &c, 1);
    if (n < 0) {
      write(2, "$ ", 2);
      continue;
    }
    if (n == 0)
      return -1;
    buf[i++] = c;
    if (c == '\n')
      break;
  }
  buf[i] = 0;
  return 0;
}

int
main(void)
{
  static char buf[100];
  int fd;

  setpgid(0, getpid());
  tcsetpgrp(getpgid());
  sigaction(SIGINT, SIG_IGN);
  sigaction(SIGTSTP, SIG_IGN);

  // Ensure that three file descriptors are open.
  while ((fd = open("console", O_RDWR)) >= 0) {
    if (fd >= 3) {
      close(fd);
      break;
    }
  }

  // Read and run input commands.
  while (getcmd(buf, sizeof(buf)) >= 0) {
    job_refresh();
    char *cmd = buf;
    while (*cmd == ' ' || *cmd == '\t')
      cmd++;
    if (*cmd == '\n') // is a blank command
      continue;
    if (cmd[0] == 'c' && cmd[1] == 'd' && cmd[2] == ' ') {
      // Chdir must be called by the parent, not the child.
      cmd[strlen(cmd) - 1] = 0; // chop \n
      if (chdir(cmd + 3) < 0)
        fprintf(2, "cannot cd %s\n", cmd + 3);
    } else if (hasprefix(cmd, "jobs") &&
               (cmd[4] == '\n' || cmd[4] == 0 || cmd[4] == ' ')) {
      for (int i = 0; i < MAXJOBS; i++)
        if (jobs[i].active)
          printf("[%d] %s\n", jobs[i].pgid,
                 jobstate(jobs[i].pgid) == 2 ? "stopped" : "running");
    } else if (hasprefix(cmd, "fg ") || hasprefix(cmd, "bg ")) {
      int foreground = cmd[0] == 'f';
      int pgid = atoi(cmd + 3), slot = job_find(pgid);
      if (slot < 0) {
        fprintf(2, "sh: no such job %d\n", pgid);
      } else {
        killpg(pgid, SIGCONT);
        jobs[slot].stopped = 0;
        if (foreground) {
          tcsetpgrp(pgid);
          job_wait(pgid);
        }
      }
    } else {
      struct cmd *parsed = parsecmd(cmd);
      int background = parsed && parsed->type == BACK;
      struct cmd *run = background ? ((struct backcmd *)parsed)->cmd : parsed;
      int pid = fork1();
      if (pid == 0) {
        setpgid(0, getpid());
        sigaction(SIGINT, SIG_DFL);
        sigaction(SIGTSTP, SIG_DFL);
        runcmd(run);
      }
      setpgid(pid, pid);
      if (background) {
        job_add(pid, 0);
        printf("[%d] %d\n", pid, pid);
      } else {
        tcsetpgrp(pid);
        job_wait(pid);
      }
    }
  }
  exit(0);
}

void
panic(char *s)
{
  fprintf(2, "%s\n", s);
  exit(1);
}

int
fork1(void)
{
  int pid;

  pid = fork();
  if (pid == -1)
    panic("fork");
  return pid;
}

